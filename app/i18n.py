# -*- coding: utf-8 -*-
"""Локализация интерфейса VideoScribe.

Русский — базовый язык: русские строки в коде служат ключами.
Словари _UK и _EN дают переводы; tr() возвращает строку на текущем языке.

Язык задаётся в настройках (config.ui_lang): "auto" | "ru" | "uk" | "en".
"auto" определяется по языку системы: украинский → uk, русский/белорусский → ru,
иначе английский. Применяется при старте программы (main.py).
"""
from __future__ import annotations

_current = "ru"


def resolve_auto() -> str:
    """Определить язык интерфейса по языку системы."""
    loc = ""
    try:
        import locale
        loc = (locale.getlocale()[0] or "")
        if not loc:
            loc = (locale.getdefaultlocale()[0] or "")  # noqa: B028
    except Exception:
        pass
    if not loc:
        import os
        loc = os.environ.get("LANG", "") or os.environ.get("LC_ALL", "")
    loc = loc.lower().replace("-", "_")
    if loc.startswith(("uk", "ukrainian")):
        return "uk"
    if loc.startswith(("ru", "be", "russian", "belarusian")):
        return "ru"
    return "en"


def set_language(lang: str | None) -> None:
    """Установить язык интерфейса: "auto" | "ru" | "uk" | "en"."""
    global _current
    lang = (lang or "auto").strip().lower()
    if lang == "auto":
        lang = resolve_auto()
    _current = lang if lang in ("ru", "uk", "en") else "ru"


def current_language() -> str:
    return _current


def tr(text: str) -> str:
    """Перевести строку на текущий язык (ru — как есть)."""
    if _current == "uk":
        return _UK.get(text, text)
    if _current == "en":
        return _EN.get(text, text)
    return text


